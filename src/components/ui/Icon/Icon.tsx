export type IconName = keyof typeof icons;

type IconProps = Omit<LucideProps, "ref"> & { name: IconName };

export function Icon({ name, size = 20, strokeWidth = 1.75, ...props }: IconProps) {
  const Component = icons[name];
  return <Component size={size} strokeWidth={strokeWidth} aria-hidden="true" focusable="false" {...props} />;
}
